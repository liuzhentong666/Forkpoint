def connect(args, database, role=None):
    options = copy.copy(args)
    options.database, options.role = database, role
    return Connection(options)


def seed(connection):
    connection.sql("""
      BEGIN;
      SELECT vc.begin_change('main',vc.head(),'seed','4000 local experiment rows');
      INSERT INTO app.products SELECT n,'sku-'||n,'product-'||n,10,100 FROM generate_series(1,4000) n;
      SELECT vc.write_file('src/app.py',convert_to('base code','UTF8'));
      SELECT vc.finish_change(); COMMIT;
      SELECT vc.materialize(vc.head(),vc.table_id('app.products'));
    """)


def target(connection, name):
    # name is generated by this test, not arbitrary SQL input.
    revision = connection.sql(f"""
      SELECT vc.fork('{name}',vc.head()) AS base \gset
      BEGIN;
      SELECT vc.begin_change('{name}',:'base','review','maintenance scenario') AS draft \gset
      UPDATE agent.products SET stock=99 WHERE id=4000;
      SELECT vc.finish_change() AS revision \gset
      COMMIT;
      SELECT :'revision';
    """)
    return dict(revision=revision, table_id=connection.sql("SELECT vc.table_id('app.products');"))


def manager_checks(owner, manager):
    attributes = json.loads(owner.sql("""
      SELECT json_build_object('superuser',rolsuper,'createdb',rolcreatedb,'createrole',rolcreaterole,
        'replication',rolreplication,'bypassrls',rolbypassrls,'login',rolcanlogin)
      FROM pg_roles WHERE rolname='agentdb_manager';
    """))
    assert not any(attributes.values()), attributes
    assert manager.sql("SELECT current_user;") == "agentdb_manager"
    denied = {
        "read_raw_history": "SELECT * FROM vc.changeset LIMIT 1;",
        "rewrite_history": "UPDATE vc.changeset SET message='forbidden';",
        "write_snapshot_table": "DELETE FROM vc.snapshot_manifest;",
        "write_business_table": "UPDATE app.products SET price=1 WHERE id=1;",
        "create_version": "SELECT vc.begin_change('main','00000000-0000-0000-0000-000000000001');",
        "create_function": "CREATE FUNCTION vc.forbidden() RETURNS int LANGUAGE sql AS 'SELECT 1';",
        "create_role": "CREATE ROLE agentdb_review_forbidden;",
    }
    for name, statement in denied.items():
        result = manager.execute(statement)
        assert result.returncode != 0 and "42501" in result.stderr, (name, result.stdout, result.stderr)
    return dict(effective_role="agentdb_manager", attributes=attributes,
                denied_sqlstate="42501", denied_operations=list(denied))


def maintenance_checks(owner, manager):
    results = {}
    for when in ("after_intent", "after_apply"):
        goal = target(owner, "review-" + when.replace("_", "-"))
        store = MemoryStore()
        runner = SnapshotMaintenance(Runtime(Engine(store)), manager)
        def crash():
            raise InterruptedError(when)
        try:
            runner.run(when, "agent-a", **goal, **{when: crash})
        except InterruptedError:
            pass
        else:
            raise AssertionError("Crash hook was not exercised")
        snapshot_before_resume = runner.inspect(goal)["snapshot_exists"]
        assert snapshot_before_resume == (when == "after_apply")
        assert Engine(store).read(when)["state"]["status"] == "running"
        resumed = SnapshotMaintenance(Runtime(Engine(store)), manager).run(when, "agent-b", **goal)
        assert resumed["verified"] and resumed["applied"] == (when == "after_intent")
        results[when] = dict(target=goal, snapshot_before_resume=snapshot_before_resume, resumed=resumed)
    goal = target(owner, "review-zombie")
    store = MemoryStore()
    paused, release = threading.Event(), threading.Event()
    def stall():
        paused.set()
        if not release.wait(45):
            raise TimeoutError("Coordinator did not release A")
    a = SnapshotMaintenance(Runtime(Engine(store)), manager)
    b = SnapshotMaintenance(Runtime(Engine(store)), manager)
    with ThreadPoolExecutor(max_workers=1) as pool:
        asleep = pool.submit(a.run, "zombie", "agent-a", **goal, after_apply=stall)
        try:
            assert paused.wait(30)
            finished = b.run("zombie", "agent-b", **goal)
            head = Engine(store).read("zombie")
        finally:
            release.set()
        try:
            asleep.result(timeout=15)
        except Conflict:
            stale = "conflict"
        else:
            raise AssertionError("Zombie A incorrectly succeeded")
    assert Engine(store).read("zombie") == head
    assert Engine(store).history("zombie")["events"][0]["actor"] == "agent-b"
    results["zombie"] = dict(a_result=stale, b_result=finished, final_version=head["version"], target=goal)
    return results


def merge_all(owner, worker, client="session"):
    count, rows_per_agent = 10, 10
    clients, session_open_ms = [worker] * count, None
    if client == "session":
        # One long-lived psql process per writer, opened before timing starts,
        # as a connection pool would be.
        began = time.perf_counter()
        with ThreadPoolExecutor(max_workers=count) as pool:
            clients = list(pool.map(lambda _: worker.session(), range(count)))
        session_open_ms = round((time.perf_counter()-began)*1000, 3)
    try:
        return _merge_all(owner, worker, clients, client, session_open_ms, count, rows_per_agent)
    finally:
        for writer in clients:
            if writer is not worker:
                writer.close()


def _merge_all(owner, worker, clients, client, session_open_ms, count, rows_per_agent):
    base = worker.sql("SELECT vc.head();")
    history_before = int(owner.sql("SELECT count(*) FROM vc.row_change;"))
    started = time.perf_counter()
    for i in range(count):
        clients[i].sql(f"SELECT vc.fork('merge-all-{i}','{base}');")
    assert int(owner.sql("SELECT count(*) FROM vc.row_change;")) == history_before
    barrier = threading.Barrier(count)
    def propose(i):
        barrier.wait(timeout=30)
        began = time.perf_counter()
        revision = clients[i].sql(f"""
          BEGIN;
          SELECT vc.begin_change('merge-all-{i}','{base}','synthetic-{i}','ten rows and code') AS draft \gset
          UPDATE agent.products SET price={100+i} WHERE id BETWEEN {10*i+1} AND {10*i+10};
          SELECT vc.write_file('src/agent_{i}.py',convert_to('PRICE = {100+i}','UTF8')) AS hash \gset
          SELECT vc.finish_change() AS revision \gset
          COMMIT;
          SELECT :'revision';
        """)
        return dict(agent=i, revision=revision, branch_commit_wall_ms=round((time.perf_counter()-began)*1000, 3))
    with ThreadPoolExecutor(max_workers=count) as pool:
        proposals = list(pool.map(propose, range(count)))
    branches_ms = (time.perf_counter()-started)*1000
    assert worker.sql("SELECT vc.head();") == base
    assert owner.sql("SELECT bool_and(price=10) FROM app.products;") == "t"
    barrier = threading.Barrier(count)
    def land(item):
        barrier.wait(timeout=30)
        began, expected, stale, writer = time.perf_counter(), base, 0, clients[item["agent"]]
        for attempt in range(1, 31):
            result = writer.execute(f"""
              BEGIN;
              SELECT vc.merge('main','{item['revision']}','{expected}','synthetic-{item['agent']}') AS merged \gset
              COMMIT;
              SELECT :'merged';
            """)
            if result.returncode == 0:
                return dict(**item, merged_head=result.stdout.strip(), attempts=attempt, stale_head_retries=stale,
                            merge_wall_ms=round((time.perf_counter()-began)*1000, 3))
            if "40001" not in result.stderr:
                raise AssertionError(result.stderr)  # Never retry semantic/constraint conflicts blindly.
            stale += 1
            expected = writer.sql("SELECT vc.head();")
        raise AssertionError("Merge retry bound exhausted")
    merge_started = time.perf_counter()
    with ThreadPoolExecutor(max_workers=count) as pool:
        landed = list(pool.map(land, proposals))
    merge_ms = (time.perf_counter()-merge_started)*1000
    complete_ms = (time.perf_counter()-started)*1000
    final_head = worker.sql("SELECT vc.head();")
    assert owner.sql("SELECT count(*) FROM app.products;") == "4000"
    assert owner.sql("SELECT bool_and(price=100+((id-1)/10)) FROM app.products WHERE id<=100;") == "t"
    assert owner.sql("SELECT bool_and(price=10) FROM app.products WHERE id>100;") == "t"
    assert worker.sql(f"SELECT bool_and((doc->>'price')::numeric=10) FROM vc.rows_at('{base}',vc.table_id('app.products'));") == "t"
    for item in landed:
        i = item["agent"]
        assert worker.sql(f"SELECT convert_from(vc.read_file('{final_head}','src/agent_{i}.py'),'UTF8');") == f"PRICE = {100+i}"
        assert owner.sql(f"SELECT EXISTS(SELECT 1 FROM vc._ancestors('{final_head}') WHERE id='{item['revision']}');") == "t"
    assert owner.sql("SELECT count(*) FROM vc.work_tx;") == "0"
    latencies = [item["merge_wall_ms"] for item in landed]
    return dict(agents=count, actual_llm_agents=False, client=client, session_open_ms=session_open_ms,
                table_rows=4000, changed_rows=count*rows_per_agent,
                all_merged=len(landed), base=base, final_head=final_head,
                fork_copied_history_rows=0, branch_phase_wall_ms=round(branches_ms,3),
                merge_phase_wall_ms=round(merge_ms,3), end_to_end_wall_ms=round(complete_ms,3),
                merge_median_ms=round(statistics.median(latencies),3), merge_max_ms=max(latencies),
                stale_head_retries=sum(item["stale_head_retries"] for item in landed), results=landed,
                verification="100 changed rows, 3900 unchanged rows, 10 code files, 10 reachable source commits, fixed base, no unfinished transactions",
                timing_scope=("Client wall time includes lock waits, retries and final COMMIT; " +
                              ("each writer reuses one long-lived psql session opened before timing (session_open_ms)"
                               if client == "session" else "every call starts wsl.exe + psql") +
                              "; not a production throughput claim"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    add_connection_arguments(parser)
    parser.add_argument("--client", choices=("session", "spawn"), default="session",
                        help="merge-all writers: one long-lived psql session each (default), or one process per call")
    args = parser.parse_args()
    database = "agentdb_test_review_" + uuid.uuid4().hex[:10]
    owner = connect(args, database)
    details = owner.check()
    owner.create_database(database)
    owner.install()
    seed(owner)
    print("Dedicated existing-server test database: " + database, flush=True)
    # Exercise the original assertions on the new installation as well.
    run_tests.CONNECTION, run_tests.DBNAME = owner, database
    regression = run_tests.test_suite()
    manager, worker = connect(args, database, "agentdb_manager"), connect(args, database, "agentdb_client")
    permissions = manager_checks(owner, manager)
    print("PASS restricted manager permissions", flush=True)
    maintenance = maintenance_checks(owner, manager)
    print("PASS two crash windows and zombie conflict on real PostgreSQL", flush=True)
    merges = merge_all(owner, worker, args.client)
    output = dict(database=database, postgresql=details, regression_tests=len(regression),
                  manager=permissions, maintenance=maintenance, merge_all=merges,
                  real_cloud_verified=False, state_backend="MemoryStore-test-only",
                  note="Existing PostgreSQL service reused without replacement or restart; dedicated test database retained. No model used in synthetic merge benchmark.")
    (ROOT / "local-review-results.json").write_text(json.dumps(output, indent=2)+"\n", encoding="utf-8")
    print(json.dumps(output, indent=2), flush=True)


if __name__ == "__main__":
    main()
